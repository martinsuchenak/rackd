package storage

import (
	"context"
	"sort"
	"strings"
	"testing"

	"github.com/martinsuchenak/rackd/pkg/model"
)

func TestDNSRecordNamesRelativeMigration(t *testing.T) {
	s := newTestStorage(t)
	defer func() { _ = s.Close() }()
	ctx := context.Background()

	provider := &model.DNSProviderConfig{Name: "tech", Type: model.DNSProviderTypeTechnitium, Endpoint: "http://dns.example.test"}
	if err := s.CreateDNSProvider(ctx, provider); err != nil {
		t.Fatal(err)
	}
	forward := &model.DNSZone{Name: "example.test", ProviderID: provider.ID, TTL: 300}
	reverse := &model.DNSZone{Name: "1.168.192.in-addr.arpa.", ProviderID: provider.ID, TTL: 300}
	for _, z := range []*model.DNSZone{forward, reverse} {
		if err := s.CreateDNSZone(ctx, z); err != nil {
			t.Fatal(err)
		}
	}
	device := &model.Device{Name: "web-01", Hostname: "web-01"}
	if err := s.CreateDevice(ctx, device); err != nil {
		t.Fatal(err)
	}

	add := func(zoneID, name, typ, value string, linked bool) {
		t.Helper()
		r := &model.DNSRecord{ZoneID: zoneID, Name: name, Type: typ, Value: value, TTL: 300, SyncStatus: model.RecordSyncStatusPending}
		if linked {
			r.DeviceID = &device.ID
		}
		if err := s.CreateDNSRecord(ctx, r); err != nil {
			t.Fatal(err)
		}
	}
	// Imported, fully qualified.
	add(forward.ID, "Mail.Example.Test.", "A", "192.168.1.20", false)
	add(forward.ID, "example.test", "NS", "ns1.example.test", false)
	add(reverse.ID, "20.1.168.192.in-addr.arpa", "PTR", "mail.example.test", false)
	// Imported copy of a record the sync already created relatively.
	add(forward.ID, "web-01", "A", "192.168.1.10", true)
	add(forward.ID, "web-01.example.test", "A", "192.168.1.10", false)
	// Not in the zone: left as it is.
	add(forward.ID, "notexample.test", "TXT", "x", false)
	// Generated by the old sync.
	add(forward.ID, "db-01", "A", "2001:db8::5", true)
	add(forward.ID, "10.1.168.in-addr.arpa", "PTR", "web-01.example.test", true)

	if err := migrateDNSRecordNamesRelativeUp(ctx, s.db); err != nil {
		t.Fatal(err)
	}

	records, err := s.ListDNSRecords(ctx, &model.DNSRecordFilter{})
	if err != nil {
		t.Fatal(err)
	}
	var got []string
	for _, r := range records {
		zone := "fwd"
		if r.ZoneID == reverse.ID {
			zone = "rev"
		}
		got = append(got, zone+" "+r.Name+" "+r.Type)
	}
	sort.Strings(got)
	want := []string{"fwd @ NS", "fwd Mail A", "fwd notexample.test TXT", "fwd web-01 A", "rev 20 PTR"}
	if strings.Join(got, "|") != strings.Join(want, "|") {
		t.Fatalf("records after migration:\n got %v\nwant %v", got, want)
	}
}
