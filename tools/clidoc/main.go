// Command clidoc writes the CLI reference, docs/cli-reference.md, from the
// command definitions, so it can't drift from the code:
//
//	go run ./tools/clidoc > docs/cli-reference.md
//
// Its test fails when the committed file is out of date.
package main

import (
	"bytes"
	"context"
	"fmt"
	"io"
	"os"
	"strings"

	"github.com/martinsuchenak/rackd/pkg/app"
	"github.com/paularlott/cli"
)

func main() {
	out, err := reference()
	if err != nil {
		fmt.Fprintln(os.Stderr, err)
		os.Exit(1)
	}
	fmt.Print(out)
}

// reference renders every command's help, depth first.
func reference() (string, error) {
	root, err := app.Command(app.Options{})
	if err != nil {
		return "", err
	}
	var b strings.Builder
	b.WriteString("# CLI Reference\n\n")
	b.WriteString("<!-- Generated by `go run ./tools/clidoc > docs/cli-reference.md`; don't edit by hand. -->\n\n")
	b.WriteString("Every `rackd` command and its flags, as `rackd <command> --help` prints them. See [CLI](cli.md) for configuration, output formats and examples.\n")
	var walk func(path []string, cmd *cli.Command) error
	walk = func(path []string, cmd *cli.Command) error {
		if len(path) > 0 {
			help, err := helpFor(path)
			if err != nil {
				return err
			}
			fmt.Fprintf(&b, "\n%s `rackd %s`\n\n", strings.Repeat("#", min(len(path)+1, 4)), strings.Join(path, " "))
			b.WriteString("```text\n" + strings.TrimSpace(help) + "\n```\n")
		}
		for _, sub := range cmd.Commands {
			if err := walk(append(append([]string{}, path...), sub.Name), sub); err != nil {
				return err
			}
		}
		return nil
	}
	if err := walk(nil, root); err != nil {
		return "", err
	}
	return b.String(), nil
}

// helpFor runs `rackd <path> --help` on a fresh command tree and returns what
// it prints. The library prints help to stdout, so stdout is captured.
func helpFor(path []string) (string, error) {
	root, err := app.Command(app.Options{})
	if err != nil {
		return "", err
	}
	r, w, err := os.Pipe()
	if err != nil {
		return "", err
	}
	stdout, args := os.Stdout, os.Args
	os.Stdout, os.Args = w, append([]string{"rackd"}, append(path, "--help")...)
	done := make(chan []byte)
	go func() {
		var buf bytes.Buffer
		_, _ = io.Copy(&buf, r)
		done <- buf.Bytes()
	}()
	execErr := root.Execute(context.Background())
	os.Stdout, os.Args = stdout, args
	_ = w.Close()
	out := <-done
	if execErr != nil {
		return "", fmt.Errorf("rackd %s --help: %w", strings.Join(path, " "), execErr)
	}
	return string(out), nil
}
